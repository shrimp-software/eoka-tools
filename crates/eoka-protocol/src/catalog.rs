impl OperationSpec {
    pub fn cli_command(&self) -> String {
        match self.cli_override() {
            Some(command) => command.to_owned(),
            None => self.path.replace('.', " ").replace('_', "-"),
        }
    }
}

impl Request {
    pub fn is_convenience_action(&self) -> bool {
        matches!(
            self,
            Request::Click(_)
                | Request::DblClick(_)
                | Request::Fill(_)
                | Request::Select(_)
                | Request::Hover(_)
                | Request::Key(_)
                | Request::Back(_)
                | Request::Forward(_)
                | Request::HistoryGo(_)
                | Request::Reload
        )
    }

    pub fn spec(&self) -> &'static OperationSpec {
        operation_by_cmd(self.cmd()).expect("every request variant is a catalog operation")
    }
}

fn schema_for<T: schemars::JsonSchema>() -> serde_json::Value {
    serde_json::to_value(schemars::schema_for!(T))
        .unwrap_or_else(|_| serde_json::json!({ "type": "object", "additionalProperties": true }))
}
